/* =====================================================
   EXPORTERS.JS — Format meeting results for Slack, Notion, JSON
   ===================================================== */

export function formatForSlack(result) {
  let text = '*⚡ Meeting Brief — S.N.A.P.*\n\n';
  
  text += '*📌 Summary*\n' + result.summary + '\n\n';
  
  if (result.decisions?.length > 0) {
    text += '*✅ Decisions*\n';
    result.decisions.forEach((d, i) => { text += `${i + 1}. ${d}\n`; });
    text += '\n';
  }
  
  if (result.actionItems?.length > 0) {
    text += '*🎯 Action Items*\n';
    result.actionItems.forEach((item, i) => {
      const p = item.priority === 'high' ? '🔴' : item.priority === 'medium' ? '🟡' : '🟢';
      text += `${p} *${item.task}*\n`;
      text += `    → _Owner:_ ${item.owner}  |  _Deadline:_ ${item.deadline}  |  _Priority:_ ${item.priority}\n`;
    });
    text += '\n';
  }
  
  if (result.followUps?.length > 0) {
    text += '*🔄 Follow-ups*\n';
    result.followUps.forEach((f, i) => { text += `${i + 1}. ${f}\n`; });
    text += '\n';
  }
  
  if (result.healthScore?.score) {
    text += `*💊 Meeting Health:* ${result.healthScore.score}/100 — ${result.healthScore.verdict}\n`;
  }
  
  text += '\n_Generated by S.N.A.P._';
  return text;
}

export function formatForNotion(result) {
  let text = '# ⚡ Meeting Brief\n\n';
  
  text += '## 📌 Summary\n' + result.summary + '\n\n';
  
  if (result.decisions?.length > 0) {
    text += '## ✅ Decisions\n';
    result.decisions.forEach(d => { text += `- ${d}\n`; });
    text += '\n';
  }
  
  if (result.actionItems?.length > 0) {
    text += '## 🎯 Action Items\n\n';
    text += '| Status | Task | Owner | Deadline | Priority |\n';
    text += '|--------|------|-------|----------|----------|\n';
    result.actionItems.forEach(item => {
      const p = item.priority === 'high' ? '🔴 High' : item.priority === 'medium' ? '🟡 Medium' : '🟢 Low';
      text += `| ☐ | ${item.task} | ${item.owner} | ${item.deadline} | ${p} |\n`;
    });
    text += '\n';
  }
  
  if (result.followUps?.length > 0) {
    text += '## 🔄 Follow-ups\n';
    result.followUps.forEach(f => { text += `- [ ] ${f}\n`; });
    text += '\n';
  }
  
  if (result.healthScore?.score) {
    text += `## 💊 Meeting Health Score: ${result.healthScore.score}/100\n`;
    text += `> ${result.healthScore.verdict}\n\n`;
    text += `- **Clarity:** ${result.healthScore.clarity}/100\n`;
    text += `- **Actionability:** ${result.healthScore.actionability}/100\n`;
    text += `- **Participation:** ${result.healthScore.participation}/100\n\n`;
  }
  
  text += '---\n*Generated by S.N.A.P.*\n';
  return text;
}

export function formatAsJSON(result) {
  return JSON.stringify(result, null, 2);
}

export async function exportToWebhook(result, url) {
  if (!url) throw new Error('No webhook URL provided');
  
  const response = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      appName: 'S.N.A.P.',
      timestamp: new Date().toISOString(),
      eventType: 'new_meeting_analysis',
      data: result
    })
  });
  
  if (!response.ok) {
    throw new Error(`Webhook failed: ${response.statusText}`);
  }
  
  return true;
}
