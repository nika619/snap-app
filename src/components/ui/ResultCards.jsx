import { useState, useRef, useCallback } from 'react';
import {
  createActionItemEvent,
  createReminderUrl,
  createFollowUpEvent,
  openCalendarEvent
} from '../../services/calendar';
import { formatForSlack, formatForNotion, formatAsJSON, exportToWebhook } from '../../services/exporters';

function formatResultAsText(result) {
  let text = '⚡ S.N.A.P. — MEETING BRIEF\n';
  text += '━'.repeat(45) + '\n\n';
  text += '📌 SUMMARY\n' + result.summary + '\n\n';
  if (result.decisions?.length > 0) {
    text += '✅ DECISIONS\n';
    result.decisions.forEach((d, i) => { text += `  ${i + 1}. ${d}\n`; });
    text += '\n';
  }
  if (result.actionItems?.length > 0) {
    text += '🎯 ACTION ITEMS\n';
    result.actionItems.forEach((item, i) => {
      const p = item.priority === 'high' ? '🔴' : item.priority === 'medium' ? '🟡' : '🟢';
      text += `  ${i + 1}. ${p} ${item.task}\n`;
      text += `     → Owner: ${item.owner}  |  Deadline: ${item.deadline}  |  Priority: ${item.priority}\n`;
    });
    text += '\n';
  }
  if (result.followUps?.length > 0) {
    text += '🔄 FOLLOW-UPS\n';
    result.followUps.forEach((f, i) => { text += `  ${i + 1}. ${f}\n`; });
  }
  text += '\n' + '━'.repeat(45) + '\n';
  text += 'Generated by S.N.A.P.\n';
  return text;
}

function TiltCard({ children, className = '' }) {
  const ref = useRef(null);
  const onMove = useCallback((e) => {
    const el = ref.current;
    if (!el) return;
    const r = el.getBoundingClientRect();
    const x = e.clientX - r.left, y = e.clientY - r.top;
    const rx = ((y - r.height / 2) / (r.height / 2)) * -3;
    const ry = ((x - r.width / 2) / (r.width / 2)) * 3;
    el.style.transform = `perspective(1000px) rotateX(${rx}deg) rotateY(${ry}deg) translateY(-2px)`;
  }, []);
  const onLeave = useCallback(() => {
    if (ref.current) ref.current.style.transform = 'perspective(1000px) rotateX(0) rotateY(0)';
  }, []);
  return (
    <div ref={ref} className={`glass-card result-card ${className}`}
      style={{ transition: 'transform 0.12s ease-out, background 0.5s' }}
      onMouseMove={onMove} onMouseLeave={onLeave}>
      {children}
    </div>
  );
}

/* ================================
   HEALTH SCORE RING
   ================================ */
function HealthScoreRing({ score, label, color, size = 80 }) {
  const radius = (size - 8) / 2;
  const circumference = 2 * Math.PI * radius;
  const offset = circumference - (score / 100) * circumference;

  return (
    <div className="health-ring-item">
      <svg width={size} height={size} className="health-ring-svg">
        <circle cx={size/2} cy={size/2} r={radius}
          stroke="rgba(0,0,0,0.08)" strokeWidth="6" fill="none" />
        <circle cx={size/2} cy={size/2} r={radius}
          stroke={color} strokeWidth="6" fill="none"
          strokeDasharray={circumference} strokeDashoffset={offset}
          strokeLinecap="round"
          style={{ transition: 'stroke-dashoffset 1.5s ease-out', transform: 'rotate(-90deg)', transformOrigin: '50% 50%' }} />
        <text x="50%" y="50%" textAnchor="middle" dy=".35em"
          style={{ fontSize: size * 0.25, fontWeight: 700, fill: color, fontFamily: 'var(--font-headline)' }}>
          {score}
        </text>
      </svg>
      <span className="health-ring-label">{label}</span>
    </div>
  );
}

/* ================================
   EDITABLE ACTION ITEM
   ================================ */
function EditableActionItem({ item, index, onUpdate }) {
  const [editing, setEditing] = useState(false);
  const [editData, setEditData] = useState({ ...item });
  const [completed, setCompleted] = useState(item.completed || false);

  const handleSave = () => {
    onUpdate(index, { ...editData, completed });
    setEditing(false);
  };

  const handleCancel = () => {
    setEditData({ ...item });
    setEditing(false);
  };

  const toggleComplete = () => {
    const newCompleted = !completed;
    setCompleted(newCompleted);
    onUpdate(index, { ...item, completed: newCompleted });
  };

  if (editing) {
    return (
      <div className={`action-item priority-${editData.priority} action-item--editing`}>
        <div className="action-edit-fields">
          <input className="action-edit-input" value={editData.task}
            onChange={(e) => setEditData({ ...editData, task: e.target.value })}
            placeholder="Task description" />
          <div className="action-edit-row">
            <input className="action-edit-input action-edit-input--small" value={editData.owner}
              onChange={(e) => setEditData({ ...editData, owner: e.target.value })}
              placeholder="Owner" />
            <input className="action-edit-input action-edit-input--small" value={editData.deadline}
              onChange={(e) => setEditData({ ...editData, deadline: e.target.value })}
              placeholder="Deadline" />
            <select className="action-edit-select" value={editData.priority}
              onChange={(e) => setEditData({ ...editData, priority: e.target.value })}>
              <option value="high">High</option>
              <option value="medium">Medium</option>
              <option value="low">Low</option>
            </select>
          </div>
        </div>
        <div className="action-edit-actions">
          <button className="btn-cta" onClick={handleSave} style={{ padding: '0.4rem 1rem', fontSize: '0.75rem' }}>
            <span className="material-symbols-outlined" style={{ fontSize: '14px' }}>check</span> Save
          </button>
          <button className="btn-ghost" onClick={handleCancel} style={{ fontSize: '0.75rem' }}>Cancel</button>
        </div>
      </div>
    );
  }

  return (
    <div className={`action-item priority-${item.priority} ${completed ? 'action-item--completed' : ''}`}>
      <div style={{ display: 'flex', alignItems: 'flex-start', gap: '0.75rem', flex: 1 }}>
        <button className={`action-checkbox ${completed ? 'action-checkbox--checked' : ''}`}
          onClick={toggleComplete} title={completed ? 'Mark incomplete' : 'Mark complete'}>
          <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>
            {completed ? 'check_box' : 'check_box_outline_blank'}
          </span>
        </button>
        <div>
          <div className={`action-item-task ${completed ? 'action-item-task--done' : ''}`}>{item.task}</div>
          <div className="action-item-meta">
            <span className="meta-chip owner">
              <span className="material-symbols-outlined">person</span>
              {item.owner}
            </span>
            <span className="meta-chip deadline">
              <span className="material-symbols-outlined">calendar_today</span>
              {item.deadline}
            </span>
          </div>
        </div>
      </div>
      <div className="action-item-actions">
        <button className="cal-action-btn" title="Edit" onClick={() => setEditing(true)}>
          <span className="material-symbols-outlined">edit</span>
          Edit
        </button>
        <button className="cal-action-btn" title="Add to Google Calendar"
          onClick={() => openCalendarEvent(createActionItemEvent(item))}>
          <span className="material-symbols-outlined">calendar_add_on</span>
          Calendar
        </button>
        <button className="cal-action-btn cal-action-btn--remind" title="Set a quick reminder"
          onClick={() => openCalendarEvent(createReminderUrl(item))}>
          <span className="material-symbols-outlined">alarm</span>
          Remind
        </button>
        <span className={`priority-badge ${item.priority}`}>
          {item.priority === 'high' ? 'HIGH PRIORITY' : item.priority === 'medium' ? 'MEDIUM PRIORITY' : 'LOW PRIORITY'}
        </span>
      </div>
    </div>
  );
}

/* ================================
   EXPORT DROPDOWN
   ================================ */
function ExportDropdown({ result }) {
  const [open, setOpen] = useState(false);
  const [feedback, setFeedback] = useState('');

  const copyFormat = async (formatter, label) => {
    try {
      await navigator.clipboard.writeText(formatter(result));
      setFeedback(`✅ Copied as ${label}!`);
    } catch {
      setFeedback('❌ Copy failed');
    }
    setTimeout(() => { setFeedback(''); setOpen(false); }, 1500);
  };

  return (
    <div className="export-dropdown-wrap">
      <button className="btn-secondary" onClick={() => setOpen(!open)}>
        <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>ios_share</span>
        Export
        <span className="material-symbols-outlined" style={{ fontSize: '14px' }}>{open ? 'expand_less' : 'expand_more'}</span>
      </button>
      {open && (
        <div className="export-dropdown glass-card">
          <button className="export-option" onClick={() => copyFormat(formatForSlack, 'Slack')}>
            <span style={{ fontSize: '1.1rem' }}>💬</span> Copy for Slack
          </button>
          <button className="export-option" onClick={() => copyFormat(formatForNotion, 'Notion')}>
            <span style={{ fontSize: '1.1rem' }}>📝</span> Copy for Notion
          </button>
          <button className="export-option" onClick={() => copyFormat(formatAsJSON, 'JSON')}>
            <span style={{ fontSize: '1.1rem' }}>📋</span> Copy as JSON
          </button>
          {feedback && <div className="export-feedback">{feedback}</div>}
        </div>
      )}
    </div>
  );
}


/* ================================
   MAIN RESULT CARDS
   ================================ */
export default function ResultCards({ result, onReset, onUpdateResult }) {
  const [showCopied, setShowCopied] = useState(false);
  const [emailCopied, setEmailCopied] = useState(false);
  const [webhookStatus, setWebhookStatus] = useState('');

  const handleSendToWorkflow = async () => {
    const url = localStorage.getItem('briefmind_webhook_url');
    if (!url) {
      alert("Please configure your Webhook URL in Settings first.");
      return;
    }
    
    setWebhookStatus('sending');
    try {
      await exportToWebhook(result, url);
      setWebhookStatus('success');
    } catch (e) {
      console.error(e);
      setWebhookStatus('error');
    }
    setTimeout(() => setWebhookStatus(''), 3000);
  };

  const handleCopyAll = async () => {
    try {
      await navigator.clipboard.writeText(formatResultAsText(result));
    } catch {
      const ta = document.createElement('textarea');
      ta.value = formatResultAsText(result);
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      document.body.removeChild(ta);
    }
    setShowCopied(true);
    setTimeout(() => setShowCopied(false), 2500);
  };

  const handleCopyEmail = async () => {
    try {
      await navigator.clipboard.writeText(result.emailDraft);
    } catch { /* fallback */ }
    setEmailCopied(true);
    setTimeout(() => setEmailCopied(false), 2500);
  };

  const handleExportAll = () => {
    if (!result.actionItems?.length) return;
    result.actionItems.forEach((item, i) => {
      setTimeout(() => {
        openCalendarEvent(createActionItemEvent(item));
      }, i * 600);
    });
  };

  const handleUpdateActionItem = (index, updatedItem) => {
    const newItems = [...result.actionItems];
    newItems[index] = updatedItem;
    const newResult = { ...result, actionItems: newItems };
    if (onUpdateResult) onUpdateResult(newResult);
  };

  const totalItems = result.actionItems?.length || 0;
  const highPriority = result.actionItems?.filter(i => i.priority === 'high').length || 0;
  const hs = result.healthScore;

  // Speaker chart max
  const maxMentions = Math.max(...(result.speakerStats || []).map(s => s.mentions || 0), 1);

  return (
    <div className="results-section">
      {/* Toolbar */}
      <div className="results-toolbar">
        <div className="results-toolbar-left">
          <h2 className="results-title text-gradient">Meeting Brief</h2>
          <div className="results-pills">
            {totalItems > 0 && (
              <span className="results-pill results-pill--actions">{totalItems} ACTIONS</span>
            )}
            {highPriority > 0 && (
              <span className="results-pill results-pill--critical">{highPriority} CRITICAL</span>
            )}
            {hs?.score > 0 && (
              <span className="results-pill" style={{
                background: hs.score >= 70 ? 'rgba(52,211,153,0.15)' : hs.score >= 40 ? 'rgba(251,191,36,0.15)' : 'rgba(239,68,68,0.15)',
                color: hs.score >= 70 ? '#34d399' : hs.score >= 40 ? '#fbbf24' : '#ef4444'
              }}>HEALTH {hs.score}</span>
            )}
          </div>
        </div>
        <div className="results-toolbar-right">
          <ExportDropdown result={result} />
          <button 
            className="btn-secondary" 
            onClick={handleSendToWorkflow}
            disabled={webhookStatus === 'sending'}
          >
            <span className="material-symbols-outlined" style={{ fontSize: '16px', color: webhookStatus === 'success' ? '#34d399' : webhookStatus === 'error' ? '#ef4444' : 'inherit' }}>
              {webhookStatus === 'success' ? 'check_circle' : webhookStatus === 'error' ? 'error' : 'webhook'}
            </span>
            {webhookStatus === 'sending' ? 'Sending...' : webhookStatus === 'success' ? 'Sent!' : 'Send to Workflow'}
          </button>
          {totalItems > 0 && (
            <button className="btn-secondary" onClick={handleExportAll}>
              <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>calendar_month</span>
              Export All to Calendar
            </button>
          )}
          <button className="btn-secondary" onClick={handleCopyAll}>
            <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>content_copy</span>
            Copy All
          </button>
          <button className="btn-ghost" onClick={onReset}>
            <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>add</span>
            New Analysis
          </button>
        </div>
      </div>

      {/* Bento Grid */}
      <div className="bento-grid">

        {/* Health Score Card */}
        {hs && hs.score > 0 && (
          <TiltCard className="bento-full">
            <div className="card-header">
              <div className="card-icon" style={{
                background: `linear-gradient(135deg, ${hs.score >= 70 ? 'rgba(52,211,153,0.15)' : 'rgba(239,68,68,0.15)'}, transparent)`,
              }}>
                <span className="material-symbols-outlined" style={{ color: hs.score >= 70 ? '#34d399' : hs.score >= 40 ? '#fbbf24' : '#ef4444' }}>
                  monitor_heart
                </span>
              </div>
              <h3 className="card-title">Meeting Health Score</h3>
            </div>
            <div className="health-scores-row">
              <HealthScoreRing score={hs.score} label="Overall" color={hs.score >= 70 ? '#34d399' : hs.score >= 40 ? '#fbbf24' : '#ef4444'} size={100} />
              <HealthScoreRing score={hs.clarity} label="Clarity" color="#38bdf8" />
              <HealthScoreRing score={hs.actionability} label="Actionability" color="#F97316" />
              <HealthScoreRing score={hs.participation} label="Participation" color="#D946EF" />
            </div>
            <p className="health-verdict">{hs.verdict}</p>
          </TiltCard>
        )}

        {/* Summary */}
        <TiltCard className="bento-full">
          <div className="card-header">
            <div className="card-icon" style={{
              background: 'linear-gradient(135deg, rgba(249, 115, 22, 0.15), rgba(234, 88, 12, 0.1))',
              boxShadow: '0 0 15px rgba(249, 115, 22, 0.1)'
            }}>
              <span className="material-symbols-outlined" style={{ color: '#F97316' }}>format_align_left</span>
            </div>
            <h3 className="card-title">Summary</h3>
          </div>
          <p className="summary-text">{result.summary}</p>
        </TiltCard>

        {/* Decisions */}
        {result.decisions?.length > 0 && (
          <TiltCard className={result.followUps?.length > 0 ? '' : 'bento-full'}>
            <div className="card-header">
              <div className="card-icon" style={{
                background: 'linear-gradient(135deg, rgba(52, 211, 153, 0.15), rgba(52, 211, 153, 0.1))',
                boxShadow: '0 0 15px rgba(52, 211, 153, 0.1)'
              }}>
                <span className="material-symbols-outlined" style={{ color: '#34d399' }}>check_circle</span>
              </div>
              <h3 className="card-title">
                Decisions <span className="card-count">{result.decisions.length}</span>
              </h3>
            </div>
            <ul className="result-list">
              {result.decisions.map((d, i) => (
                <li key={i} className="result-list-item">
                  <span className="result-list-icon" style={{ color: '#34d399' }}>
                    <span className="material-symbols-outlined">check</span>
                  </span>
                  <span>{d}</span>
                </li>
              ))}
            </ul>
          </TiltCard>
        )}

        {/* Follow-ups */}
        {result.followUps?.length > 0 && (
          <TiltCard className={result.decisions?.length > 0 ? '' : 'bento-full'}>
            <div className="card-header">
              <div className="card-icon" style={{
                background: 'linear-gradient(135deg, rgba(250, 204, 21, 0.15), rgba(234, 179, 8, 0.1))',
                boxShadow: '0 0 15px rgba(250, 204, 21, 0.1)'
              }}>
                <span className="material-symbols-outlined" style={{ color: '#d97706' }}>trend_flat</span>
              </div>
              <h3 className="card-title">
                Follow-ups <span className="card-count">{result.followUps.length}</span>
              </h3>
            </div>
            <ul className="result-list">
              {result.followUps.map((f, i) => (
                <li key={i} className="result-list-item">
                  <span className="result-list-icon" style={{ color: '#d97706' }}>
                    <span className="material-symbols-outlined">trending_flat</span>
                  </span>
                  <span className="result-list-text">{f}</span>
                  <button
                    className="cal-action-btn"
                    title="Schedule follow-up in calendar"
                    onClick={(e) => { e.stopPropagation(); openCalendarEvent(createFollowUpEvent(f)); }}
                  >
                    <span className="material-symbols-outlined">calendar_add_on</span>
                    Schedule
                  </button>
                </li>
              ))}
            </ul>
          </TiltCard>
        )}

        {/* Action Items — EDITABLE */}
        {result.actionItems?.length > 0 && (
          <TiltCard className="bento-full">
            <div className="card-header">
              <div className="card-icon" style={{
                background: 'linear-gradient(135deg, rgba(251, 191, 36, 0.15), rgba(251, 191, 36, 0.1))',
                boxShadow: '0 0 15px rgba(251, 191, 36, 0.1)'
              }}>
                <span className="material-symbols-outlined" style={{ color: '#b45309' }}>target</span>
              </div>
              <h3 className="card-title">
                Action Items <span className="card-count">{result.actionItems.length}</span>
              </h3>
            </div>
            <div className="action-items-list">
              {result.actionItems.map((item, i) => (
                <EditableActionItem key={i} item={item} index={i} onUpdate={handleUpdateActionItem} />
              ))}
            </div>
          </TiltCard>
        )}

        {/* Speaker Analytics */}
        {result.speakerStats?.length > 0 && (
          <TiltCard className="bento-full">
            <div className="card-header">
              <div className="card-icon" style={{
                background: 'linear-gradient(135deg, rgba(56, 189, 248, 0.15), rgba(56, 189, 248, 0.1))',
                boxShadow: '0 0 15px rgba(56, 189, 248, 0.1)'
              }}>
                <span className="material-symbols-outlined" style={{ color: '#38bdf8' }}>groups</span>
              </div>
              <h3 className="card-title">
                Speaker Analytics <span className="card-count">{result.speakerStats.length}</span>
              </h3>
            </div>
            <div className="speaker-stats-list">
              {result.speakerStats.map((speaker, i) => (
                <div key={i} className="speaker-stat-row">
                  <div className="speaker-info">
                    <span className="speaker-name">{speaker.name}</span>
                    <span className="speaker-role">{speaker.role}</span>
                  </div>
                  <div className="speaker-bar-wrap">
                    <div className="speaker-bar" style={{
                      width: `${(speaker.mentions / maxMentions) * 100}%`,
                      background: `linear-gradient(90deg, #38bdf8, #D946EF)`
                    }} />
                  </div>
                  <div className="speaker-chips">
                    <span className="speaker-chip">{speaker.actionItems} tasks</span>
                    <span className="speaker-chip">{speaker.decisions} decisions</span>
                    <span className="speaker-chip">{speaker.mentions} mentions</span>
                  </div>
                </div>
              ))}
            </div>
          </TiltCard>
        )}

        {/* Email Draft */}
        {result.emailDraft && (
          <TiltCard className="bento-full">
            <div className="card-header">
              <div className="card-icon" style={{
                background: 'linear-gradient(135deg, rgba(217, 70, 239, 0.15), rgba(217, 70, 239, 0.1))',
                boxShadow: '0 0 15px rgba(217, 70, 239, 0.1)'
              }}>
                <span className="material-symbols-outlined" style={{ color: '#D946EF' }}>mail</span>
              </div>
              <h3 className="card-title">Follow-up Email Draft</h3>
            </div>
            <pre className="email-draft-text">{result.emailDraft}</pre>
            <div className="email-draft-actions">
              <button className="btn-secondary" onClick={handleCopyEmail}>
                <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>content_copy</span>
                {emailCopied ? 'Copied!' : 'Copy Email'}
              </button>
              <button className="btn-secondary" onClick={() => {
                const subject = encodeURIComponent('Meeting Follow-up - ' + new Date().toLocaleDateString());
                const body = encodeURIComponent(result.emailDraft);
                window.open(`https://mail.google.com/mail/?view=cm&fs=1&su=${subject}&body=${body}`, '_blank');
              }}>
                <span className="material-symbols-outlined" style={{ fontSize: '16px' }}>open_in_new</span>
                Open in Gmail
              </button>
            </div>
          </TiltCard>
        )}
      </div>

      {showCopied && <div className="copy-feedback">✅ Copied to clipboard</div>}
    </div>
  );
}
